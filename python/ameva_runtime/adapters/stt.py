def _calculate_whisper_layers(engine: Any = None) -> int:
    """Calculates GPU offload layers for Whisper models."""
    if engine is not None:
        if hasattr(engine, "gpu_layers") and getattr(engine, "gpu_layers", 0) > 0:
            return int(engine.gpu_layers)
        if hasattr(engine, "config") and hasattr(engine.config, "gpu_layers") and engine.config.gpu_layers > 0:
            return int(engine.config.gpu_layers)
    return 32


def _calc_file_sha256(path: Path) -> str:
    """Computes SHA-256 hex digest of a file in 1MB chunks."""
    digest = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().lower()


def has_vulkan_link_hint(path: Any) -> bool:
    """Static Heuristic Pre-filter (Notice: NOT a conclusive capability verification).
    Verifies that the file is a 64-bit ARM64 ELF binary and contains string hints of
    Vulkan compute libraries (libvulkan.so or libggml-vulkan).
    """
    p = Path(path).expanduser().resolve(strict=False)
    if not p.is_file():
        return False
    try:
        with open(p, "rb") as f:
            header = f.read(64)
            if len(header) < 20 or not header.startswith(b"\x7fELF"):
                return False
            is_64 = header[4] == 2
            is_little = header[5] == 1
            machine = int.from_bytes(header[18:20], "little" if is_little else "big")
            # 183 is AArch64
            if not (is_64 and is_little and machine == 183):
                return False
            content = header + f.read(8 * 1024 * 1024)
            return (b"libvulkan.so" in content) or (b"libggml-vulkan" in content)
    except Exception as exc:
        logger.warning("[ameva-runtime:SttAdapter] has_vulkan_link_hint failed on %s: %s", p, exc)
        return False


def verify_stt_manifest(
    binary_path: Path,
    manifest_path: Optional[Path] = None,
) -> Dict[str, Any]:
    """Verifies that the binary and its dependent runtime libraries match the cryptographic manifest
    generated by NativeAssetManager.
    """
    home = Path(os.environ.get("HOME", os.path.expanduser("~")))
    prefix = Path(os.environ.get("PREFIX", "/data/data/com.termux/files/usr"))
    prefix_manifest = prefix / "share" / "ameva" / "manifests" / "stt.json"
    default_manifest = home / ".local" / "share" / "ameva" / "manifests" / "stt.json"
    release_manifest = home / ".local" / "share" / "ameva" / "current" / "stt" / "manifest.json"

    target_manifest = manifest_path or (prefix_manifest if prefix_manifest.is_file() else default_manifest)
    if manifest_path is None and not target_manifest.is_file():
        if prefix_manifest.is_file():
            target_manifest = prefix_manifest
        elif release_manifest.is_file():
            target_manifest = release_manifest

    # P0-1: If manifest is missing, fail immediately without silent bypass
    if not target_manifest.is_file():
        raise AmevaRuntimeError(
            f"STT deployment manifest is missing: '{target_manifest}'. "
            "Refusing unverified Vulkan binary under Zero-Silent-Fallback policy."
        )

    try:
        with open(target_manifest, "r", encoding="utf-8") as f:
            data = json.load(f)
    except Exception as exc:
        raise AmevaRuntimeError(f"Failed to read STT installer manifest at '{target_manifest}': {exc}") from exc

    # 1. Verify bundle metadata
    backend_feat = data.get("backend_feature")
    if not backend_feat and "vulkan" in data.get("components", []):
        backend_feat = "vulkan"
    if backend_feat != "vulkan":
        raise AmevaRuntimeError(
            f"Manifest integrity error: backend_feature is '{data.get('backend_feature')}', expected 'vulkan'"
        )
    target_arch = data.get("target_architecture") or "aarch64"
    if target_arch != "aarch64":
        raise AmevaRuntimeError(
            f"Manifest integrity error: target_architecture is '{target_arch}', expected 'aarch64'"
        )

    # 2. Verify primary binary SHA-256
    manifest_bin_sha = data.get("binary_sha256") or data.get("sha256", "")
    if not manifest_bin_sha:
        raise AmevaRuntimeError("Manifest integrity error: missing binary_sha256 in manifest")

    actual_bin_sha = _calc_file_sha256(binary_path)
    if actual_bin_sha.lower() != manifest_bin_sha.lower():
        raise AmevaRuntimeError(
            f"Cryptographic hash mismatch for '{binary_path}': "
            f"expected={manifest_bin_sha}, actual={actual_bin_sha}. Potential binary tampering or corruption."
        )

    # 3. P0-3: Validate ALL regular files in deployed_files (not just .suffix == '.so')
    bundle_root = target_manifest.parent
    for rel_path, entry in data.get("deployed_files", {}).items():
        deployed_path = Path(entry.get("path", "")).resolve(strict=False)
        if not deployed_path.is_file():
            deployed_path = (bundle_root / rel_path).resolve(strict=False)
        expected_sha = entry.get("sha256", "").lower()

        if not deployed_path.is_file():
            raise AmevaRuntimeError(
                f"Required deployed file missing: '{deployed_path}' (rel_path: '{rel_path}')"
            )

        actual_sha = _calc_file_sha256(deployed_path)
        if actual_sha.lower() != expected_sha:
            raise AmevaRuntimeError(
                f"Deployed file integrity violation for '{deployed_path}': "
                f"expected={expected_sha}, actual={actual_sha}"
            )

    return data


def resolve_single_explicit_candidate(engine: Any) -> Optional[Path]:
    """Extracts a single explicit binary candidate from engine configuration, if any."""
    if engine is None:
        return None
    # 1. engine.config.extra["binary_path"]
    if hasattr(engine, "config") and hasattr(engine.config, "extra") and isinstance(engine.config.extra, dict):
        if val := engine.config.extra.get("binary_path"):
            return Path(val)
    # 2. engine.binary_path
    if hasattr(engine, "binary_path") and getattr(engine, "binary_path"):
        return Path(getattr(engine, "binary_path"))
    # 3. engine.whisper_bin
    if hasattr(engine, "whisper_bin") and getattr(engine, "whisper_bin"):
        return Path(getattr(engine, "whisper_bin"))
    return None


def resolve_unmanaged_whisper_binary_for_development(engine: Any = None) -> Path:
    """Diagnostic utility for local manual development: resolves explicit binary candidate without manifest.
    STRICTLY FORBIDDEN IN PRODUCTION ENGINE BINDINGS.
    """
    target = resolve_single_explicit_candidate(engine)
    if target is None:
        raise AmevaRuntimeError("No explicit candidate provided for unmanaged development resolution")
    resolved = target.expanduser().resolve(strict=False)
    if not resolved.is_file():
        raise AmevaRuntimeError(f"Explicit development binary missing: {resolved}")
    if not has_vulkan_link_hint(resolved):
        raise AmevaRuntimeError(f"Explicit development binary lacks Vulkan link hints: {resolved}")
    return resolved


def resolve_whisper_binary(
    engine: Any = None,
    manifest_path: Optional[Path] = None,
) -> Path:
    """Resolves and validates the whisper-cli executable via Single Explicit Priority & Canonical SSOT.

    Policy:
      - If explicit binary_path is provided: validate THAT path only. Fail immediately on error;
        NEVER fall back to canonical path.
      - Manifest verification is strictly mandatory in production.
      - If NO explicit candidate is provided: validate canonical binary ($PREFIX/bin/whisper-cli)
        and verify against Installer manifest.
    """
    explicit_candidate = resolve_single_explicit_candidate(engine)
    if explicit_candidate is not None:
        target = explicit_candidate.expanduser().resolve(strict=False)
        if not target.is_file():
            raise AmevaRuntimeError(
                f"[ERROR: AMEVA-STT-E002] Explicit STT binary does not exist or is not a file: '{target}'"
            )
        if not has_vulkan_link_hint(target):
            raise AmevaRuntimeError(
                f"Required Vulkan linkage hint was not found in '{target}'. "
                "The binary is not accepted by AMEVA Vulkan policy."
            )

        explicit_manifest = manifest_path
        if not explicit_manifest and engine is not None:
            if getattr(engine, "manifest_path", None):
                explicit_manifest = Path(engine.manifest_path)
            elif hasattr(engine, "config") and hasattr(engine.config, "extra") and isinstance(engine.config.extra, dict):
                if m_val := engine.config.extra.get("manifest_path"):
                    explicit_manifest = Path(m_val)

        # In production, explicit candidate strictly requires its own explicit manifest
        if explicit_manifest is None:
            raise AmevaRuntimeError(
                f"STT deployment manifest is missing: '{target}'. "
                "Refusing unverified Vulkan binary under Zero-Silent-Fallback policy."
            )

        # In production, manifest verification is strictly mandatory
        verify_stt_manifest(target, manifest_path=explicit_manifest)
        return target

    # No explicit candidate provided: evaluate canonical binary strictly
    home = Path(os.environ.get("HOME", os.path.expanduser("~")))
    prefix = Path(os.environ.get("PREFIX", "/data/data/com.termux/files/usr"))
    prefix_bin = (prefix / "bin" / "whisper-cli").resolve(strict=False)
    local_bin = (home / ".local" / "bin" / "whisper-cli").resolve(strict=False)
    canonical_bin = prefix_bin if prefix_bin.is_file() else (local_bin if local_bin.is_file() else prefix_bin)

    if not canonical_bin.is_file():
        raise AmevaRuntimeError(
            f"[ERROR: AMEVA-STT-E002] No Vulkan-accelerated whisper-cli binary found at canonical path "
            f"('{canonical_bin}').\n"
            f"Action Required: Run 'python -m ameva_runtime.installer --asset stt' to provision the verified Vulkan engine."
        )

    if not has_vulkan_link_hint(canonical_bin):
        raise AmevaRuntimeError(
            f"Required Vulkan linkage hint was not found in '{canonical_bin}'. "
            "The binary is not accepted by AMEVA Vulkan policy."
        )

    verify_stt_manifest(canonical_bin, manifest_path=manifest_path)
    return canonical_bin


@dataclass(frozen=True)
class SttDeviceQuirks:
    disable_fp16: bool = False
    force_medium_matmul: bool = False
    quirk_applied: bool = False
    reason: str = ""


# Verified Device & Driver Quirk Table based on empirical driver behavior
STT_QUIRK_REGISTRY = [
    {
        "vendor_id": 0x13B5,  # ARM
        "device_pattern": r"(?i)Mali-G78",
        "disable_fp16": True,
        "force_medium_matmul": True,
        "reason": "Mali-G78 (Exynos 2100) driver bug: FP16 subgroup matrix precision corruption in ggml-vulkan",
    },
    {
        "vendor_id": 0x13B5,  # ARM
        "device_pattern": r"(?i)Mali-G68",
        "disable_fp16": True,
        "force_medium_matmul": True,
        "reason": "Mali-G68 (Exynos 1380) driver bug: medium matmul and FP16 disable required",
    },
]


def resolve_stt_quirks(report: Any, profile: Any = None) -> SttDeviceQuirks:
    """Resolves device-specific hardware quirks using empirical quirk table.
    Does NOT disable FP16 for all Mali GPUs indiscriminately.
    """
    dev_name = str(getattr(report, "device_name", "") or "")
    soc = str(getattr(profile, "soc_model", "") or "")
    vendor_id = getattr(report, "vendor_id", 0)
    diagnosis = str(getattr(profile, "diagnosis_reason", "") or "")

    for entry in STT_QUIRK_REGISTRY:
        if entry["vendor_id"] and vendor_id and vendor_id != entry["vendor_id"]:
            continue
        pat = entry["device_pattern"]
        if re.search(pat, dev_name) or re.search(pat, soc) or re.search(pat, diagnosis):
            return SttDeviceQuirks(
                disable_fp16=entry["disable_fp16"],
                force_medium_matmul=entry["force_medium_matmul"],
                quirk_applied=True,
                reason=entry["reason"],
            )

    return SttDeviceQuirks(
        disable_fp16=False,
        force_medium_matmul=False,
        quirk_applied=False,
        reason="No hardware quirks matched; native FP16 compute permitted",
    )


