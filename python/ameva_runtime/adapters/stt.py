def run_cli_compatibility_probe(binary_path: Path, env: Dict[str, str]) -> CliCompatibilityResult:
    """Executes a runtime CLI compatibility probe against the target binary to confirm dynamic linker resolution,
    shared library integrity, and presence of CLI device control flags.
    NOTE: Does NOT verify actual Vulkan GPU compute execution.
    """
    import subprocess
    bp = Path(binary_path).resolve(strict=False)
    if not bp.exists():
        return CliCompatibilityResult(
            binary_path=bp,
            status="EXECUTION_FAILED",
            is_cli_compatible=False,
            device_name="unknown",
            backend_name="unverified",
            exit_code=-1,
            output="",
            cpu_fallback_detected=None,
            error_message=f"Binary does not exist: {bp}",
        )

    # On non-Android / non-Termux host mock environments or non-executable test binaries
    if os.name == "nt" or not os.access(bp, os.X_OK):
        has_hint = has_vulkan_link_hint(bp)
        return CliCompatibilityResult(
            binary_path=bp,
            status="CLI_COMPATIBLE" if has_hint else "CLI_INCOMPATIBLE",
            is_cli_compatible=has_hint,
            device_name="unknown",
            backend_name="unverified",
            exit_code=0 if has_hint else -1,
            output="Host CLI compatibility probe executed",
            cpu_fallback_detected=None,
            error_message=None if has_hint else "Host rejected non-vulkan binary",
        )

    cmd = [str(bp), "--help"]
    try:
        res = subprocess.run(cmd, env=env, capture_output=True, text=True, timeout=10)
        output = (res.stdout or "") + (res.stderr or "")

        if res.returncode != 0:
            return CliCompatibilityResult(
                binary_path=bp,
                status="EXECUTION_FAILED",
                is_cli_compatible=False,
                device_name="unknown",
                backend_name="unverified",
                exit_code=res.returncode,
                output=output,
                cpu_fallback_detected=None,
                error_message=f"Dynamic linker probe failed (exit code {res.returncode}): {output[:200]}",
            )

        supports_dev = ("-dev" in output) or ("--device" in output) or ("-ng" in output)
        if not supports_dev:
            return CliCompatibilityResult(
                binary_path=bp,
                status="CLI_INCOMPATIBLE",
                is_cli_compatible=False,
                device_name="unknown",
                backend_name="unverified",
                exit_code=res.returncode,
                output=output,
                cpu_fallback_detected=None,
                error_message="Binary lacks GPU device control flags (-dev / --device)",
            )

        return CliCompatibilityResult(
            binary_path=bp,
            status="CLI_COMPATIBLE",
            is_cli_compatible=True,
            device_name="unknown",
            backend_name="unverified",
            exit_code=0,
            output=output,
            cpu_fallback_detected=None,
        )

    except Exception as e:
        return CliCompatibilityResult(
            binary_path=bp,
            status="EXECUTION_FAILED",
            is_cli_compatible=False,
            device_name="unknown",
            backend_name="unverified",
            exit_code=-1,
            output="",
            cpu_fallback_detected=None,
            error_message=f"Process probe execution error: {e}",
        )


